function entry = makeEntry(rootDir, caseName, analysisType, netlistFile, operatingPointAudit, waveformAudit, toleranceName, expectedFail)
entry = struct( ...
    'caseName', string(caseName), ...
    'analysisType', string(analysisType), ...
    'netlistPath', fullfile(rootDir, 'examples', 'netlists', netlistFile), ...
    'baseline', "legacy", ...
    'operatingPointAudit', operatingPointAudit, ...
    'waveformAudit', waveformAudit, ...
    'probeSelection', "all", ...
    'toleranceProfile', toleranceProfile(toleranceName), ...
    'expectedFail', logical(expectedFail));
end

function audit = baselineLis(fileName)
audit = struct('kind', "hspiceLis", 'path', fullfile("fixtures", "hspice", fileName));
end

function audit = baselineTr0(fileName)
audit = struct('kind', "hspiceTr0", 'path', fullfile("fixtures", "hspice", fileName));
end

function audit = baselineNone()
audit = struct('kind', "none", 'path', "");
end

function profile = toleranceProfile(name)
switch string(name)
    case {"dcDefault", "dcsweepDefault"}
        profile = struct( ...
            'name', string(name), ...
            'nodeAbs', 1e-3, ...
            'currentAbs', 1e-6, ...
            'magnitudeRel', 0.02, ...
            'phaseAbsDeg', 2, ...
            'waveformAbs', 1e-2, ...
            'waveformCurrentAbs', 1e-4);
    case "acDefault"
        profile = struct( ...
            'name', string(name), ...
            'nodeAbs', 1e-3, ...
            'currentAbs', 1e-6, ...
            'magnitudeRel', 0.02, ...
            'phaseAbsDeg', 2, ...
            'waveformAbs', 1e-2, ...
            'waveformCurrentAbs', 1e-4);
    case "transientDefault"
        profile = struct( ...
            'name', string(name), ...
            'nodeAbs', 1e-3, ...
            'currentAbs', 1e-6, ...
            'magnitudeRel', 0.02, ...
            'phaseAbsDeg', 2, ...
            'waveformAbs', 1e-2, ...
            'waveformCurrentAbs', 1e-4);
    otherwise
        error('spice:regression:UnknownToleranceProfile', 'Unknown tolerance profile %s.', string(name));
end
end
