function entries = manifest(rootDir)
% MANIFEST Define the native-vs-legacy regression matrix.
% Each entry is the single source of truth for a regression case, its
% baseline, tolerances, HSPICE audit input, and whether the case is still a
% known expected failure while native accuracy work is in progress.
if nargin < 1 || strlength(string(rootDir)) == 0
    rootDir = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
end
rootDir = string(rootDir);

entries = [ ...
    makeEntry(rootDir, "bufferDC", "dc", "bufferDC.sp", baselineLis("buffer.lis"), baselineNone(), "dcDefault", true) ...
    makeEntry(rootDir, "bjtAmplifierDC", "dc", "bjtAmplifierDC.sp", baselineLis("bjtamplifierdc.lis"), baselineNone(), "dcDefault", true) ...
    makeEntry(rootDir, "dbmixerDC", "dc", "dbmixerDC.sp", baselineLis("dbmixer.lis"), baselineNone(), "dcDefault", false) ...
    makeEntry(rootDir, "diftestDC", "dc", "diftestDC.sp", baselineLis("diftest.lis"), baselineNone(), "dcDefault", false) ...
    makeEntry(rootDir, "bufferAC", "ac", "bufferAC.sp", baselineLis("bufferac.lis"), baselineNone(), "acDefault", true) ...
    makeEntry(rootDir, "bjtAmplifierAC", "ac", "bjtAmplifierAC.sp", baselineNone(), baselineNone(), "acDefault", true) ...
    makeEntry(rootDir, "SmosAC", "ac", "SmosAC.sp", baselineLis("smosac.lis"), baselineNone(), "acDefault", true) ...
    makeEntry(rootDir, "dbmixerAC", "ac", "dbmixerAC.sp", baselineLis("dbmixerac.lis"), baselineNone(), "acDefault", true) ...
    makeEntry(rootDir, "bufferSweep", "dcsweep", "bufferSweep.sp", baselineLis("buffer.lis"), baselineNone(), "dcsweepDefault", true) ...
    makeEntry(rootDir, "bjtAmplifierSweep", "dcsweep", "bjtAmplifierSweep.sp", baselineLis("bjtamplifierdc.lis"), baselineNone(), "dcsweepDefault", true) ...
    makeEntry(rootDir, "invertbufferSweep", "dcsweep", "invertbufferSweep.sp", baselineLis("inverterbuffer.lis"), baselineNone(), "dcsweepDefault", true) ...
    makeEntry(rootDir, "diftestSweep", "dcsweep", "diftestSweep.sp", baselineLis("diftest.lis"), baselineNone(), "dcsweepDefault", false) ...
    makeEntry(rootDir, "bufferTrans", "trans", "bufferTrans.sp", baselineLis("buffertrans.lis"), baselineNone(), "transientDefault", true) ...
    makeEntry(rootDir, "bjtAmplifierTrans", "trans", "bjtAmplifierTrans.sp", baselineLis("bjtamplifiertrans.lis"), baselineNone(), "transientDefault", true) ...
    makeEntry(rootDir, "dbmixerTrans", "trans", "dbmixerTrans.sp", baselineLis("dbmixertrans.lis"), baselineNone(), "transientDefault", true) ...
    makeEntry(rootDir, "diftestTrans", "trans", "diftestTrans.sp", baselineLis("diftesttrans.lis"), baselineNone(), "transientDefault", true) ...
    makeEntry(rootDir, "bufferTransDynamic", "trans", "bufferTrans.sp", baselineLis("buffertrans.lis"), baselineNone(), "transientDefault", true) ...
    makeEntry(rootDir, "bjtAmplifierTransDynamic", "trans", "bjtAmplifierTrans.sp", baselineLis("bjtamplifiertrans.lis"), baselineNone(), "transientDefault", true) ...
    makeEntry(rootDir, "bufferTransDynamicTR", "trans", "bufferTransDynamicTR.sp", baselineLis("buffertrans.lis"), baselineTr0("buffertrans.tr0"), "transientDefault", true) ...
    makeEntry(rootDir, "bjtAmplifierTransDynamicTR", "trans", "bjtAmplifierTransDynamicTR.sp", baselineLis("bjtamplifiertrans.lis"), baselineTr0("bjtamplifiertrans.tr0"), "transientDefault", true) ...
    makeEntry(rootDir, "bufferShoot", "shoot", "bufferShoot.sp", baselineNone(), baselineNone(), "transientDefault", true) ...
